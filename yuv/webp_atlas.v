module yuv

import math

// Keep full-size luma and half-size chroma in different channels of one
// texture. Chroma occupies its top-left quarter, with edge extension over
// the remaining texels. Sampling at half the luma coordinates gives chroma
// its own derivatives and filtering without first reconstructing RGB.
pub fn webp_420_atlas_upload(planes []u8, width int, height int) ?[]u8 {
	if width <= 0 || height <= 0 || width > 4096 || height > 4096
		|| width * height > 4 * 1024 * 1024 {
		return none
	}
	ys := width * height
	cw, ch := (width + 1) / 2, (height + 1) / 2
	cs := cw * ch
	if planes.len != ys + 2 * cs { return none }
	mut packed := []u8{len: ys * 4}
	for y in 0 .. height {
		cy := if y < ch { y } else { ch - 1 }
		for x in 0 .. width {
			cx := if x < cw { x } else { cw - 1 }
			i := y * width + x
			packed[i * 4] = planes[i]
			packed[i * 4 + 1] = planes[ys + cy * cw + cx]
			packed[i * 4 + 2] = planes[ys + cs + cy * cw + cx]
			packed[i * 4 + 3] = 255
		}
	}
	return packed
}

// Near-half draws use chroma level zero, including ceiling-sized planes for
// odd luma dimensions. Sampling still maps luma texel coordinates by one half.
// Stronger minification retains original planes only when the scaled decode
// would need another mip.
// Multiples of four align luma levels 0..2 and chroma levels 0..1 in the atlas;
// strict quarter/half bounds keep later odd-sized chroma levels unselected.
pub fn webp_atlas_sampling_supported(width int, height int, dw f64, dh f64) bool {
	if width <= 0 || height <= 0 || width > 4096 || height > 4096 || width * height > 4 * 1024 * 1024
		|| !math.is_finite(dw) || !math.is_finite(dh)
		|| dw <= 0 || dh <= 0 {
		return false
	}
	// Uniform magnification uses the original planes without mips. Keep its
	// destination integral and bounded to the verified one-to-two scale range.
	if dw > width && dh > height {
		return dw <= width * 2 && dh <= height * 2
			&& dw == math.floor(dw) && dh == math.floor(dh)
			&& dw * height == dh * width
	}
	if dw >= width || dh >= height { return false }
	if dw * 2 > width && dh * 2 > height { return true }
	return width % 4 == 0 && height % 4 == 0 && dw * 4 > width && dh * 4 > height && dw * 2 < width && dh * 2 < height
		&& math.log2(math.max(f64(width) / 2 / dw, f64(height) / 2 / dh)) >= .5
}

// A generated mip's last chroma texel is an average of source texels. Its
// padding must repeat that new value, rather than the original plane's edge.
// Luma and alpha, including their padding, retain their generated bytes.
pub fn webp_atlas_extend_mip_chroma(pixels []u8, width int, height int, cw int, ch int) ?[]u8 {
	if width <= 0 || height <= 0 || width > 4096 || height > 4096 || width * height > 4 * 1024 * 1024
		|| cw <= 0 || ch <= 0 || cw > width || ch > height || pixels.len != width * height * 4 {
		return none
	}
	mut extended := pixels.clone()
	for py in 0 .. height {
		for px in 0 .. width {
			if px < cw && py < ch { continue }
			cx, cy := math.min(px, cw - 1), math.min(py, ch - 1)
			i, j := (py * width + px) * 4, (cy * width + cx) * 4
			extended[i + 1] = pixels[j + 1]
			extended[i + 2] = pixels[j + 2]
		}
	}
	return extended
}
