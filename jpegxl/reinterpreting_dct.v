fn reinterpreting_multiply_add(a f32, b f32, c f32, fused bool) f32 {
	if fused { return fused_f32(a, b, c) }
	product := a * b
	return product + c
}

fn reinterpreting_dct_vector(input []f32, fused bool) ![]f32 {
	return match input.len {
		1 { input.clone() }
		2 { reinterpreting_dct_2(input) }
		4 { reinterpreting_dct_4(input, fused) }
		8 { reinterpreting_dct_8(input, fused) }
		16 { reinterpreting_dct_16(input, fused) }
		32 { reinterpreting_dct_32(input, fused) }
		else { return error('Invalid JPEG XL LF DCT vector size') }
	}
}


