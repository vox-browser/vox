module buildtools

import os
import time
import json2 as json

fn wrap_function(source string, signature string, before string, after string) !string {
	start, end := function_span(source, signature)!
	body := source[start..end].all_after('{').trim_string_right('}')
	// A selected compiler may already use this staged runtime. These hooks
	// save one allocator pointer and are not reentrant: wrapping them twice
	// restores nil on the second leave. Preserve a complete existing wrapper,
	// and reject partial/duplicated instrumentation instead of extending it.
	hooks := ['closure_metadata_enter()', 'closure_metadata_leave()']
	if hooks.any(body.contains(it)) {
		expected := before + after
		complete := (before == '' || body.trim_space().starts_with(before.trim_space()))
			&& (after == '' || body.trim_space().ends_with(after.trim_space()))
		if !complete || hooks.any(body.count(it) != expected.count(it)) {
			return error('Unsupported closure metadata wrapper: ${signature}')
		}
		return source
	}
	return source[..start] + signature + ' {\n' + before + body + after + '}\n' + source[end..]
}

fn glyph_index_initializer(source string) !string {
	start, end := function_span(source, 'pub fn (mut tf TTF_File) init()')!
	original := source[start..end].all_after('{').trim_string_right('}')
	if original.count('tf.read_cmap_table()') != 1 || original.count('tf.read_offset_tables()') != 1 {
		return error('Unsupported x.ttf initializer')
	}
	body := original.replace('tf.read_cmap_table()', '// Unicode lookup belongs to the caller.').replace('tf.read_offset_tables()', 'tf.read_normalized_offset_tables()')
	first, last := function_span(source, 'fn (mut tf TTF_File) read_offset_tables()')!
	mut directory := source[first..last].all_after('{').trim_string_right('}')
	if directory.count('tf.calc_checksum(') != 1 {
		return error('Unsupported x.ttf table checksum')
	}
	lines := directory.split_into_lines()
	mut out := []string{}
	mut removed := 0
	for i := 0; i < lines.len; i++ {
		if trimmed_eq(lines[i], "if tag != 'head' {") && i + 2 < lines.len && trimmed_eq(lines[i + 1], 'assert tf.calc_checksum(tf.tables[tag].offset, tf.tables[tag].length) == tf.tables[tag].checksum') && trimmed_eq(lines[i + 2], '}') {
			i += 2
			removed++
			continue
		}
		out << lines[i]
	}
	if removed != 1 { return error('Unsupported x.ttf directory checksum assertion') }
	directory = out.join('\n') + if directory.ends_with('\n') { '\n' } else { '' }
	return 'module ttf\n\n// For bounds-checked sfnt buffers normalized by decode_outline_face().\n// Preserve metadata, outlines and kerning; omit dense Unicode caches\n// and the immediate recheck of the checksums the caller just computed.\npub fn (mut tf TTF_File) init_for_glyph_indices() {' + body + '}\n\nfn (mut tf TTF_File) read_normalized_offset_tables() {' + directory + '}\n'
}

fn widen_loca(source string) !string {
	old := ['offset = tf.get_u16() << 1', 'next = tf.get_u16() << 1']
	if source.count(old[0]) == 0 && source.count(old[1]) == 0 { return source }
	if source.count(old[0]) != 1 || source.count(old[1]) != 1 {
		return error('Unsupported x.ttf loca reader')
	}
	return source.replace(old[0], old[0].replace('tf.get_u16() << 1', 'u32(tf.get_u16()) << 1')).replace(old[1], old[1].replace('tf.get_u16() << 1', 'u32(tf.get_u16()) << 1'))
}

fn prepare_font(selected string) !string {
	tmp := temporary(os.temp_dir(), 'vox-font-root-')!
	defer { remove(tmp) or {} }
	vlib := compiler_vlib(selected, tmp)!
	source := join(vlib, 'x/ttf')
	mut inputs := map[string]string{}
	for path in files(source)! { inputs[relative(path, source)] = read(path)! }
	inputs['ttf.v'] = widen_loca(inputs['ttf.v'])!
	inputs['vox_glyph_index_init.v'] = glyph_index_initializer(inputs['ttf.v'])!
	// The manifest authenticates both paths as well as the generated bytes.
	// Include those identities in the key so equal font sources from another
	// compiler cannot collide with, and reject, an otherwise intact cache.
	mut bytes := read(@FILE)! + '\x00' + real(selected) + '\x00' + vlib
	mut hashes := map[string]string{}
	mut names := inputs.keys()
	names.sort()
	for name in names {
		bytes += name + '\x00' + inputs[name]
		hashes[name] = hash(inputs[name])
	}
	sha := hash(bytes)
	root := build_cache('v/font-runtime', sha)
	identity := map[string]json.Any{
		'compiler': real(selected)
		'vlib':     vlib
		'sha256':   sha
		'files':    record_strings(hashes)
	}
	mkdir(os.dir(root))!
	mut held := acquire(root + '.lock', false)!
	defer { held.release() }
	if exists(root) {
		if maybe_load(join(root, 'manifest.json')) != identity {
			return error('Modified staged font runtime')
		}
		for name, data in inputs {
			if read(join(root, 'x/ttf', name))! != data {
				return error('Modified staged font file: ${name}')
			}
		}
	} else {
		staged := temporary(os.dir(root), 'font-')!
		defer { remove(staged) or {} }
		for name, data in inputs { write_changed(join(staged, 'x/ttf', name), data)! }
		write_json(join(staged, 'manifest.json'), json.Any(identity))!
		os.rename(staged, root)!
	}
	os.utime(root, time.now().unix(), time.now().unix())!
	return root
}

fn patch_allocator(allocation string, prealloc string) !(string, string) {
	used := allocation.contains('prealloc_realloc_copy_size(')
	defined := prealloc.contains('fn prealloc_realloc_copy_size(')
	if used && defined { return allocation, prealloc }
	if used || defined || !prealloc.contains('fn prealloc_realloc(') {
		return error('Unsupported V allocator: bounded v_realloc cannot be staged')
	}
	start, end := function_span(allocation, 'pub fn v_realloc(b &u8, n int) &u8')!
	body := replace_once(allocation[start..end], 'new_ptr = malloc(n)\n\t\t\tC.memcpy(new_ptr, b, n)', 'copy_size := prealloc_realloc_copy_size(b, n)\n\t\t\tnew_ptr = malloc(n)\n\t\t\tif copy_size > 0 { C.memcpy(new_ptr, b, copy_size) }')!
	helper := read(join(root_dir(), 'tools/prealloc_runtime/bounded_realloc.c.v'))!
	return allocation[..start] + body + allocation[end..], prealloc + '\n' + helper.all_after('module builtin\n')
}

fn capture_declarations(source string, header string) string {
	declaration := '#include ' + json.encode(real(header))
	mut text := source
	for name in ['VMODROOT', 'VEXEROOT'] {
		text = text.replace('#include "@${name}/vlib/os/execute_capture_legacy.h"', declaration)
	}
	footer := '// Staged by tools/prepare_prealloc_runtime.py: os sources resolve outside\n// this compiler root, so V does not declare their native capture helpers.\n' + declaration + '\n'
	if text.contains(footer) { return text }
	return text.trim_right('\n') + '\n\n' + footer
}

fn prepare_prealloc(selected string, output_root string) !string {
	resolved := real(os.find_abs_path_of_executable(selected) or { selected })
	tmp := temporary(os.temp_dir(), 'vox-prealloc-root-')!
	defer { remove(tmp) or {} }
	vlib := compiler_vlib(resolved, tmp)!
	builtin := join(vlib, 'builtin')
	allocation, prealloc := patch_allocator(read(join(builtin, 'allocation.c.v'))!, read(join(builtin, 'prealloc.c.v'))!)!
	mut inputs := map[string]string{}
	mut owned := map[string]string{}
	for path in listing(builtin)! {
		if os.is_file(path) { inputs['builtin/' + os.file_name(path)] = read(path)! }
	}
	for path in listing(join(builtin, 'closure'))! {
		if os.is_file(path) { inputs['builtin/closure/' + os.file_name(path)] = read(path)! }
	}
	if 'builtin/closure/closure.c.v' !in inputs {
		return error('Prealloc requires current V closure runtime')
	}
	owned['builtin/allocation.c.v'] = allocation
	owned['builtin/prealloc.c.v'] = prealloc
	owned['builtin/closure/closure_prealloc_metadata.c.v'] = read(join(root_dir(), 'tools/prealloc_runtime/closure_prealloc_metadata.c.v'))!
	compat := join(builtin, 'c_headers_compat_nix.c.v')
	capture_header := join(vlib, 'os/execute_capture_legacy.h')
	if os.is_file(compat) && os.is_file(capture_header) {
		owned['builtin/c_headers_compat_nix.c.v'] = capture_declarations(read(compat)!, capture_header)
		inputs['os/execute_capture_legacy.h'] = read(capture_header)!
	}
	for name, data in inputs {
		if !name.starts_with('builtin/closure/') { continue }
		mut text := data
		if name.ends_with('/closure.c.v') {
			text = wrap_function(text, 'fn closure_init_body()', '\tclosure_metadata_enter()\n', '\tclosure_metadata_leave()\n')!
		} else if os.file_name(name) in ['closure_nix.c.v', 'closure_windows.c.v'] {
			text = wrap_function(text, 'fn closure_mtx_lock_platform()', '', '\tclosure_metadata_enter()\n')!
			text = wrap_function(text, 'fn closure_mtx_unlock_platform()', '\tclosure_metadata_leave()\n', '')!
		}
		owned[name] = text
	}
	for name, data in owned { inputs[name] = data }
	compiler_hash := digest(resolved)!
	mut bytes := real(vlib) + compiler_hash
	mut names := inputs.keys()
	names.sort()
	for name in names { bytes += name + '\x00' + inputs[name] }
	bytes += read(@FILE)!
	sha := hash(bytes)
	mkdir(output_root)!
	root := join(real(output_root), sha)
	mut owned_hashes := map[string]string{}
	for name, data in owned { owned_hashes[name] = hash(data) }
	identity := map[string]json.Any{
		'compiler':        resolved
		'compiler_sha256': compiler_hash
		'vlib':            real(vlib)
		'sha256':          sha
		'owned_files':     record_strings(owned_hashes)
	}
	mkdir(os.dir(root))!
	mut held := acquire(root + '.lock', false)!
	defer { held.release() }
	if exists(root) {
		mut recorded := load(join(root, 'manifest.json'))!
		recorded['compiler'] = resolved
		if recorded != identity || real(join(root, 'compiler/vlib/builtin')) != join(root, 'builtin') || digest(join(root, 'compiler/v'))! != compiler_hash {
			return error('Incomplete or modified staged V runtime: ${root}')
		}
		for name, sha2 in owned_hashes {
			if digest(join(root, name))! != sha2 {
				return error('Modified staged V runtime file: ${name}')
			}
		}
	} else {
		staged := temporary(os.dir(root), 'runtime-')!
		defer { remove(staged) or {} }
		mkdir(join(staged, 'builtin/closure'))!
		for path in listing(builtin)! {
			name := 'builtin/' + os.file_name(path)
			if os.file_name(path) != 'closure' && name !in owned {
				link_to(join(staged, name), path)!
			}
		}
		for name, data in owned { write_changed(join(staged, name), data)! }
		compiler_root := join(staged, 'compiler')
		mkdir(join(compiler_root, 'vlib'))!
		for path in listing(vlib)! {
			name := os.file_name(path)
			link_to(join(compiler_root, 'vlib', name), if name == 'builtin' {
				join(root, 'builtin')
			} else {
				path
			})!
		}
		for name in ['thirdparty', 'cmd', 'v.mod'] {
			if exists(join(os.dir(vlib), name)) {
				link_to(join(compiler_root, name), join(os.dir(vlib), name))!
			}
		}
		os.cp(resolved, join(compiler_root, 'v'))!
		os.chmod(join(compiler_root, 'v'), 0o755)!
		write_json(join(staged, 'manifest.json'), json.Any(identity))!
		os.rename(staged, root)!
	}
	os.utime(root, time.now().unix(), time.now().unix())!
	return root
}
