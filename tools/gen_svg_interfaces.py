#!/usr/bin/env python3
"""Generate compact/svg_interfaces.v from Ladybird's SVG IDL and element factory.

The compact bridge exposes the SVG interface objects, their inheritance and
constants, and gives SVG elements the prototype of the interface that the
element factory creates for their local name.

usage: tools/gen_svg_interfaces.py [LADYBIRD_LIBWEB_DIR] > compact/svg_interfaces.v
"""
import glob
import json
import os
import re
import sys

libweb = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/code/3rd/ladybird/Libraries/LibWeb')

interfaces = {}
for path in sorted(glob.glob(os.path.join(libweb, 'SVG', '*.idl'))):
    text = re.sub(r'//[^\n]*', '', open(path).read())
    for match in re.finditer(r'(\[[^\]]*\]\s*)?(partial\s+)?interface\s+(mixin\s+)?(\w+)\s*(?::\s*(\w+))?\s*\{(.*?)\};', text, re.S):
        attributes, partial, mixin, name, parent, body = match.group(1) or '', match.group(2), match.group(3), match.group(4), match.group(5), match.group(6)
        if partial or mixin or 'LegacyNoInterfaceObject' in attributes:
            continue
        if attributes and 'Exposed' in attributes and not re.search(r'Exposed=(Window|\([^)]*Window[^)]*\)|\*)', attributes):
            continue
        constants = {}
        for constant in re.finditer(r'const\s+[\w ]+?\s+(\w+)\s*=\s*(0x[0-9A-Fa-f]+|-?\d+)\s*;', body):
            constants[constant.group(1)] = int(constant.group(2), 0)
        interfaces[name] = {'parent': parent, 'constants': constants}

# Parents before children.
ordered = []
def visit(name):
    if name in ordered or name not in interfaces:
        return
    visit(interfaces[name]['parent'])
    ordered.append(name)
for name in sorted(interfaces):
    visit(name)

factory = open(os.path.join(libweb, 'DOM', 'ElementFactory.cpp')).read()
start = factory.index('SVG::TagNames::svg')
tags = {}
current = None
for line in factory[start:].splitlines():
    tag = re.search(r'SVG::TagNames::(\w+)\)', line)
    if tag:
        current = tag.group(1).rstrip('_')
        continue
    created = re.search(r'create\w*<SVG::(SVG\w+)>', line)
    if created and current:
        if created.group(1) in interfaces:
            tags[current] = created.group(1)
        current = None
    if 'MathML' in line:
        break

entries = [[name, interfaces[name]['parent'], interfaces[name]['constants']] for name in ordered]
data = json.dumps({'interfaces': entries, 'tags': tags}, separators=(',', ':'), sort_keys=True)
assert "'" not in data

print('''module main

// Generated by tools/gen_svg_interfaces.py from Ladybird's SVG IDL and
// element factory; do not edit.
//
// The SVG interface objects with their inheritance and constants. SVG
// elements take the prototype of the interface their local name creates.
fn compact_svg_interfaces_bootstrap() string {
	return r\'
const __compactSVGInterfaces=Object.create(null);
(function(){
 const data=''' + data + ''';
 for(const [name,parentName,constants] of data.interfaces){
  if(Object.prototype.hasOwnProperty.call(globalThis,name))continue;
  const parent=parentName?globalThis[parentName]:null;
  if(parentName&&typeof parent!=="function")continue;
  const constructor=({[name]:function(){throw new TypeError("Illegal constructor");}})[name];
  if(parent){Object.setPrototypeOf(constructor,parent);Object.setPrototypeOf(constructor.prototype,parent.prototype);}
  for(const [constant,value] of Object.entries(constants)){
   Object.defineProperty(constructor,constant,{value,enumerable:true});
   Object.defineProperty(constructor.prototype,constant,{value,enumerable:true});
  }
  Object.defineProperty(constructor,"prototype",{writable:false});
  Object.defineProperty(constructor.prototype,Symbol.toStringTag,{value:name,configurable:true});
  Object.defineProperty(globalThis,name,{value:constructor,writable:true,configurable:true});
 }
 for(const [tag,name] of Object.entries(data.tags))if(typeof globalThis[name]==="function")__compactSVGInterfaces[tag]=globalThis[name];
})();
\'
}''')
