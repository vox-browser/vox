#!/usr/bin/env python3
"""Regenerate the macOS ANGLE dispatch table from native_egl.h."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source=(ROOT / 'webgl/native_egl.h').read_text()
names=sorted(set(re.findall(r'\b(?:egl|gl)[A-Z][A-Za-z0-9_]+',source)))
preamble='''// Generated by tools/generate_angle_dispatch.py; do not edit by hand.
// ANGLE entry points used by native_egl.h. Keep the complete API table local
// until the first WebGL context request; ordinary documents need no GL driver.
#pragma once
#ifdef __APPLE__
#include <dispatch/dispatch.h>
#include <dlfcn.h>
#include <stdio.h>
#include <stdlib.h>
#define VOX_ANGLE_FUNCTIONS(X) \\
'''
s=preamble+' \\\n'.join('    X('+n+')' for n in names)+'''

typedef struct {
#define VOX_ANGLE_FIELD(name) __typeof__(&name) name;
    VOX_ANGLE_FUNCTIONS(VOX_ANGLE_FIELD)
#undef VOX_ANGLE_FIELD
    void *egl_library, *gles_library;
    int ready;
} VoxANGLEAPI;
static VoxANGLEAPI vox_angle_api;
static int vox_angle_prepare(void) {
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        VoxANGLEAPI *api = &vox_angle_api;
        api->egl_library = dlopen("@rpath/libEGL.dylib", RTLD_LAZY | RTLD_LOCAL);
        api->gles_library = dlopen("@rpath/libGLESv2.dylib", RTLD_LAZY | RTLD_LOCAL);
        int complete = api->egl_library && api->gles_library;
#define VOX_ANGLE_RESOLVE(name) \\
        api->name = (__typeof__(api->name))dlsym(#name[0] == 'e' ? api->egl_library : api->gles_library, #name); \\
        if (!api->name) complete = 0;
        if (complete) { VOX_ANGLE_FUNCTIONS(VOX_ANGLE_RESOLVE) }
#undef VOX_ANGLE_RESOLVE
        api->ready = complete;
        if (!complete) {
            if (api->gles_library) dlclose(api->gles_library);
            if (api->egl_library) dlclose(api->egl_library);
            api->egl_library = api->gles_library = NULL;
        }
        if (getenv("VOX_WEBGL_BACKEND_DIAGNOSTICS"))
            fprintf(stderr, "VOX_WEBGL_BACKEND ready=%d\\n", complete);
    });
    return vox_angle_api.ready;
}
// Diagnostic control for matched cold-start attribution on one executable.
__attribute__((constructor)) static void vox_angle_eager_diagnostic(void) {
    if (getenv("VOX_EAGER_WEBGL_BACKEND")) (void)vox_angle_prepare();
}
#undef VOX_ANGLE_FUNCTIONS
'''
s+='\n'.join('#define '+n+' vox_angle_api.'+n for n in names)+'\n#endif\n'
output = ROOT / 'webgl/angle_dispatch_darwin.h'
if args.check:
    if output.read_text() != s:
        raise SystemExit('ANGLE dispatch table is stale; run tools/generate_angle_dispatch.py')
else:
    output.write_text(s)
    print('Generated', len(names), 'dispatch entries')
