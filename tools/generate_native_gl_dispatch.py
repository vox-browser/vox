#!/usr/bin/env python3
"""Regenerate the Windows native OpenGL entry-point table."""

from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
sources = [ROOT / "webgl/native_egl.h"] + [
    path for path in (ROOT / "webgl").glob("native_gl_*.h")
    if not path.name.startswith("native_gl_dispatch_")
]
names = set()
for source in sources:
    if source.exists():
        names.update(re.findall(r"\bgl[A-Z][A-Za-z0-9_]+", source.read_text()))

# The common adapter must call core APIs, never vendor-specific entry points.
names = {
    name for name in names
    if not name.startswith("glX") and not name.endswith(("ANGLE", "OES", "EXT"))
}
names.update(("glGetStringi", "glGetIntegerv", "glGenVertexArrays", "glBindVertexArray",
              "glDeleteVertexArrays"))
names = sorted(names)

lines = [
    "// Generated by tools/generate_native_gl_dispatch.py; do not edit by hand.",
    "// Windows resolves core entry points from the current native OpenGL driver.",
    "#ifndef VOX_WEBGL_NATIVE_GL_DISPATCH_WINDOWS_H",
    "#define VOX_WEBGL_NATIVE_GL_DISPATCH_WINDOWS_H",
    "#include <GL/glcorearb.h>",
    "",
    "typedef struct {",
]
lines += [f"    PFN{name.upper()}PROC {name[2:]};" for name in names]
lines += [
    "} VoxNativeGLAPI;",
    "",
    "static PROC vox_native_wgl_proc(char const* name)",
    "{",
    "    PROC address = wglGetProcAddress(name);",
    "    if (!address || address == (PROC)1 || address == (PROC)2 ||",
    "        address == (PROC)3 || address == (PROC)-1)",
    "        address = GetProcAddress(GetModuleHandleA(\"opengl32.dll\"), name);",
    "    return address;",
    "}",
    "",
    "static int vox_native_wgl_load(VoxNativeGLAPI* api)",
    "{",
]
for name in names:
    lines += [
        f"    api->{name[2:]} = (PFN{name.upper()}PROC)vox_native_wgl_proc(\"{name}\");",
        f"    if (!api->{name[2:]}) return 0;",
    ]
lines += ["    return 1;", "}", ""]
lines += [f"#define {name} (vox_native_gl_current()->gl.{name[2:]})" for name in names]
lines += ["#endif", ""]
(ROOT / "webgl/native_gl_dispatch_windows.h").write_text("\n".join(lines))
