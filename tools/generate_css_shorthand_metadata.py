#!/usr/bin/env python3
"""Translate Ladybird's generated CSS shorthand relationship tables to V.

The preferred order of shorthands is generated by GenerateCSSPropertyID.cpp
and is observable through CSS declaration-block serialization. Read the
generated C++ output rather than independently reimplementing that ordering.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from css_translation_extensions import extend_shorthand_tables


FUNCTION = re.compile(
    r"Vector<PropertyID> const& (?P<name>longhands_for_shorthand|expanded_longhands_for_shorthand|shorthands_for_longhand)"
    r"\(PropertyID property_id\)\s*\{(?P<body>.*?)\n\}",
    re.DOTALL,
)
BOOLEAN_FUNCTION = re.compile(
    r"bool (?P<name>property_needs_layout_for_getcomputedstyle|"
    r"property_needs_layout_node_for_resolved_value)"
    r"\(PropertyID property_id\)\s*\{(?P<body>.*?)\n\}",
    re.DOTALL,
)
CASE = re.compile(
    r"case PropertyID::(?P<property>[A-Za-z0-9]+):\s*\{\s*"
    r"static Vector<PropertyID> (?:longhands|shorthands) = \{(?P<values>.*?)\};\s*"
    r"return (?:longhands|shorthands);\s*\}",
    re.DOTALL,
)
PROPERTY = re.compile(r"PropertyID::([A-Za-z0-9]+)")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--ladybird",
        type=Path,
        default=Path.home() / "code/3rd/ladybird",
    )
    parser.add_argument(
        "--translation",
        type=Path,
        default=Path(__file__).resolve().parents[1],
    )
    parser.add_argument(
        "--ladybird-build",
        type=Path,
        default=None,
        help="generated PropertyID.cpp (defaults to Build/release, then distribution)",
    )
    return parser.parse_args()


def cpp_property_to_v(name: str) -> str:
    snake = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
    if snake == "float":
        return "float_"
    return snake


def generated_property_id_cpp(args: argparse.Namespace) -> Path:
    if args.ladybird_build is not None:
        return args.ladybird_build
    candidates = (
        args.ladybird / "Build/release/Lagom/Libraries/LibWeb/CSS/PropertyID.cpp",
        args.ladybird / "Build/distribution/Lagom/Libraries/LibWeb/CSS/PropertyID.cpp",
    )
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    raise SystemExit("generated Ladybird PropertyID.cpp was not found")


def extract_tables(source: str) -> dict[str, list[tuple[str, list[str]]]]:
    tables: dict[str, list[tuple[str, list[str]]]] = {}
    for function in FUNCTION.finditer(source):
        entries: list[tuple[str, list[str]]] = []
        for case in CASE.finditer(function.group("body")):
            entries.append(
                (
                    cpp_property_to_v(case.group("property")),
                    [cpp_property_to_v(value) for value in PROPERTY.findall(case.group("values"))],
                )
            )
        tables[function.group("name")] = entries
    required = {
        "longhands_for_shorthand",
        "expanded_longhands_for_shorthand",
        "shorthands_for_longhand",
    }
    if tables.keys() != required:
        raise SystemExit(f"failed to extract generated shorthand tables: {tables.keys()}")
    return tables


def extract_boolean_tables(source: str) -> dict[str, list[str]]:
    tables: dict[str, list[str]] = {}
    for function in BOOLEAN_FUNCTION.finditer(source):
        body = function.group("body")
        true_branch = body.split("return true;", 1)[0]
        tables[function.group("name")] = [
            cpp_property_to_v(value) for value in PROPERTY.findall(true_branch)
        ]
    required = {
        "property_needs_layout_for_getcomputedstyle",
        "property_needs_layout_node_for_resolved_value",
    }
    if tables.keys() != required:
        raise SystemExit(f"failed to extract generated property boolean tables: {tables.keys()}")
    return tables


def emit_function(name: str, entries: list[tuple[str, list[str]]]) -> list[str]:
    lines = [f"pub fn generated_{name}(property_id PropertyID) []PropertyID {{", "\treturn match property_id {"]
    for property_name, values in entries:
        serialized = ", ".join(f".{value}" for value in values)
        lines.extend((f"\t\t.{property_name} {{", f"\t\t\t[{serialized}]", "\t\t}"))
    lines.extend(("\t\telse { []PropertyID{} }", "\t}", "}", ""))
    return lines


def emit_boolean_function(name: str, properties: list[str]) -> list[str]:
    cases = ", ".join(f".{property_name}" for property_name in properties)
    return [
        f"pub fn generated_{name}(property_id PropertyID) bool {{",
        "\treturn match property_id {",
        f"\t\t{cases} {{ true }}",
        "\t\telse { false }",
        "\t}",
        "}",
        "",
    ]


def generate(source_path: Path) -> str:
    source = source_path.read_text()
    tables = extend_shorthand_tables(extract_tables(source))
    boolean_tables = extract_boolean_tables(source)
    output = [
        "// Generated from Ladybird's generated LibWeb/CSS/PropertyID.cpp by",
        "// tools/generate_css_shorthand_metadata.py. Do not edit by hand.",
        "module css",
        "",
    ]
    for name in (
        "longhands_for_shorthand",
        "expanded_longhands_for_shorthand",
        "shorthands_for_longhand",
    ):
        output.extend(emit_function(name, tables[name]))
    for name in (
        "property_needs_layout_for_getcomputedstyle",
        "property_needs_layout_node_for_resolved_value",
    ):
        output.extend(emit_boolean_function(name, boolean_tables[name]))
    return "\n".join(output)


def main() -> int:
    args = parse_args()
    source = generated_property_id_cpp(args)
    target = args.translation / "css/property_shorthand_metadata.v"
    target.write_text(generate(source))
    print(f"translated CSS shorthand metadata from {source}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
