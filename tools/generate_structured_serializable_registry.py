#!/usr/bin/env python3
"""Copy the pinned source serializable interface registry and fresh IDL ordinals."""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import sys

PIN = "963d46a829f3e1b79f44dba9d02afb70654300fa"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--source", type=Path, default=Path.home() / "code/3rd/ladybird")
parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "html/structured_serializable_registry.v")
args = parser.parse_args()
source = args.source.resolve()
if subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip() != PIN:
    raise SystemExit("The source checkout does not match the pinned translation revision")
# Import the actual source parser/generator without writing upstream bytecode.
sys.dont_write_bytecode = True
sys.path.insert(0, str(source / "Meta"))
from Utils.webidl_parser import parse_module
from Utils.utils import title_case_to_snake_case
from Generators.libweb_bindings.intrinsics import collect_interface_sets

idl_list = source / "Libraries/LibWeb/idl_files.cmake"
serialize_source = source / "Libraries/LibWeb/HTML/StructuredSerialize.cpp"
types_source = source / "Libraries/LibWeb/HTML/StructuredSerializeTypes.h"
paths = re.findall(r"libweb_js_bindings\(([^)]+)\)", idl_list.read_text())
modules = []
inputs = [idl_list, serialize_source, types_source,
          source / "Meta/Utils/webidl_parser.py",
          source / "Meta/Generators/libweb_bindings/intrinsics.py"]
for relative in paths:
    path = source / "Libraries/LibWeb" / f"{relative}.idl"
    if not path.exists():
        # These generated files declare only a partial namespace and an
        # interface mixin, so neither contributes an InterfaceName ordinal.
        if relative not in {"CSS/GeneratedCSSNumericFactoryMethods", "CSS/GeneratedCSSStyleProperties"}:
            raise SystemExit(f"Missing source IDL: {path}")
        continue
    inputs.append(path)
    modules.append(parse_module(path, path.read_text()))
subprocess.run(["git", "-C", str(source), "diff", "--quiet", PIN, "--",
                *(str(path.relative_to(source)) for path in inputs)], check=True)
interfaces = collect_interface_sets(modules).intrinsics
ordinals = {interface.name: index for index, interface in enumerate(interfaces, 1)}
registry_text = serialize_source.read_text().split("s_serializable_storage_registry =", 1)[1].split("});", 1)[0]
entries = re.findall(r'Bindings::InterfaceName::(\w+), "(\w+)"sv', registry_text)
version = re.search(r"serializable_payload_version = (\d+);", types_source.read_text())
if len(entries) != 16 or version is None or any(name not in ordinals for name, _ in entries):
    raise SystemExit("Unexpected pinned source registry structure")
digest = hashlib.sha256()
for path in inputs:
    digest.update(str(path.relative_to(source)).encode() + b"\0" + path.read_bytes() + b"\0")
lines = ["// Copyright (c) 2026, Ladybird contributors", "// SPDX-License-Identifier: BSD-2-Clause",
         "// Generated by tools/generate_structured_serializable_registry.py.",
         f"// Source pin: {PIN}", f"// Source metadata SHA256: {digest.hexdigest()}",
         "// Fresh source InterfaceName ordinals; no upstream build-header dependency.",
         "module html", "", "pub enum StructuredSerializableInterface as u16 {"]
for name, _ in entries:
    lines.append(f"\t{title_case_to_snake_case(name)} = {ordinals[name]}")
lines.extend(["}", "", f"const structured_serializable_payload_version = u64({version[1]})", "",
              "pub fn structured_serializable_interface_name(value StructuredSerializableInterface) string {", "\treturn match value {"])
for name, identifier in entries:
    lines.append(f"\t\t.{title_case_to_snake_case(name)} {{ '{identifier}' }}")
lines.extend(["\t}", "}", "", "fn structured_serializable_interface_from_u16(value u16) !StructuredSerializableInterface {", "\treturn match value {"])
for name, _ in entries:
    lines.append(f"\t\t{ordinals[name]} {{ .{title_case_to_snake_case(name)} }}")
lines.extend(["\t\telse { return error('DataCloneError: invalid structured serialize interface name') }", "\t}", "}", "",
              "fn structured_serializable_interface_from_name(value string) !StructuredSerializableInterface {", "\treturn match value {"])
for name, identifier in entries:
    lines.append(f"\t\t'{identifier}' {{ .{title_case_to_snake_case(name)} }}")
lines.extend(["\t\telse { return error('DataCloneError: unknown structured serialize interface name') }", "\t}", "}", ""])
args.output.write_text("\n".join(lines))
print(f"Copied {len(entries)} serializable ids from {len(interfaces)} fresh source intrinsics to {args.output}")
