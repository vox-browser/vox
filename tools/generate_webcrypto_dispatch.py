#!/usr/bin/env python3
"""Generate the typed macOS OpenSSL table used by WebCrypto's native adapters."""
import argparse
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
headers = sorted((root / 'webcrypto').glob('native_*.h'))
source = '\n'.join(p.read_text() for p in headers)
includes = '''#include <openssl/evp.h>
#include <openssl/core_names.h>
#include <openssl/param_build.h>
#include <openssl/params.h>
#include <openssl/bn.h>
#include <openssl/rsa.h>
#include <openssl/ec.h>
#include <openssl/kdf.h>
#if OPENSSL_VERSION_NUMBER >= 0x30200000L
#include <openssl/thread.h>
#endif
'''
cflags = subprocess.check_output(['pkg-config', '--cflags', 'openssl'], text=True).split()
macros = subprocess.check_output(['clang', *cflags, '-dM', '-E', '-x', 'c', '-'], input=includes, text=True)
macro_names = set(re.findall(r'^#define (\w+)', macros, re.M))
names = set(re.findall(r'\b((?:EVP|BN|OSSL|EC|ECDSA|OPENSSL|CRYPTO|RSA|d2i|i2d)_[A-Za-z0-9_]+)\s*\(', source))
names -= macro_names
# These function-like macros expand inside the native adapters. Include their
# actual ABI calls, while leaving the original OpenSSL macros untouched.
names.update(['BN_num_bits', 'CRYPTO_free', 'CRYPTO_malloc'])
names = sorted(names)
guard = lambda n: '#if OPENSSL_VERSION_NUMBER >= 0x30200000L\n' if n == 'OSSL_set_max_threads' else ''
end = lambda n: '#endif\n' if guard(n) else ''
s = '''// Generated by tools/generate_webcrypto_dispatch.py; do not edit by hand.
#pragma once
#ifdef __APPLE__
''' + includes + '''#include <pthread.h>
#include <dlfcn.h>
#include <stdio.h>
#include <stdlib.h>

#define VOX_CRYPTO_STRING_(value) #value
#define VOX_CRYPTO_STRING(value) VOX_CRYPTO_STRING_(value)
#ifndef VOX_WEBCRYPTO_LIBRARY_PATH
#if defined(__aarch64__)
#define VOX_WEBCRYPTO_LIBRARY_PATH "/opt/homebrew/opt/openssl@" VOX_CRYPTO_STRING(OPENSSL_VERSION_MAJOR) "/lib/libcrypto." VOX_CRYPTO_STRING(OPENSSL_VERSION_MAJOR) ".dylib"
#else
#define VOX_WEBCRYPTO_LIBRARY_PATH "/usr/local/opt/openssl@" VOX_CRYPTO_STRING(OPENSSL_VERSION_MAJOR) "/lib/libcrypto." VOX_CRYPTO_STRING(OPENSSL_VERSION_MAJOR) ".dylib"
#endif
#endif

typedef struct {
'''
for name in names:
    s += guard(name) + f'    __typeof__(&{name}) {name};\n' + end(name)
s += '''    void* library;
    int ready;
} VoxCryptoAPI;
static VoxCryptoAPI vox_crypto_api;
static pthread_once_t vox_crypto_once = PTHREAD_ONCE_INIT;
static void vox_crypto_load(void)
{
    VoxCryptoAPI* api = &vox_crypto_api;
    char const* selected = getenv("VOX_WEBCRYPTO_LIBRARY");
    api->library = dlopen(selected ? selected : VOX_WEBCRYPTO_LIBRARY_PATH, RTLD_LAZY | RTLD_LOCAL);
    if (!api->library && !selected)
        api->library = dlopen("@rpath/libcrypto." VOX_CRYPTO_STRING(OPENSSL_VERSION_MAJOR) ".dylib", RTLD_LAZY | RTLD_LOCAL);
    int complete = api->library != NULL;
    if (api->library) {
'''
for name in names:
    s += guard(name) + f'        api->{name} = (__typeof__(api->{name}))dlsym(api->library,"{name}");\n        if (!api->{name}) complete = 0;\n' + end(name)
s += '''    }
    api->ready = complete;
    // No function pointer can be used after a partial resolution failure.
    if (!complete && api->library) { dlclose(api->library); api->library = NULL; }
    if (getenv("VOX_WEBCRYPTO_BACKEND_DIAGNOSTICS"))
        fprintf(stderr,"VOX_WEBCRYPTO_BACKEND ready=%d\\n",complete);
}
static int vox_crypto_prepare(void)
{
    pthread_once(&vox_crypto_once,vox_crypto_load);
    return vox_crypto_api.ready;
}
__attribute__((constructor)) static void vox_crypto_eager_diagnostic(void)
{
    if (getenv("VOX_EAGER_WEBCRYPTO_BACKEND")) (void)vox_crypto_prepare();
}
'''
for name in names:
    s += guard(name) + f'#define {name} vox_crypto_api.{name}\n' + end(name)
s += '''#else
static int vox_crypto_prepare(void) { return 1; }
#endif
'''
output = root / 'webcrypto/openssl_dispatch_darwin.h'
if args.check:
    if output.read_text() != s:
        raise SystemExit('WebCrypto dispatch is stale; run tools/generate_webcrypto_dispatch.py')
else:
    output.write_text(s)
    print(f'Generated {len(names)} typed OpenSSL entries')
