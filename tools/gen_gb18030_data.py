#!/usr/bin/env python3
"""Generate encoding/gb18030_data.v: WHATWG's index-gb18030 and its ranges.

The indexes are read back from the encoding_rs crate (the decoder Ladybird
uses), which implements the Encoding Standard's gb18030 decoder including the
GB18030-2022 changes. Every two-byte and four-byte BMP pointer is decoded and
the four-byte results are compressed into the standard's (pointer, code point)
range starts. Needs cargo and the crate in the local registry (works offline).

usage: tools/gen_gb18030_data.py [--crate-version 0.8.40] [--output encoding/gb18030_data.v]
"""
import argparse
import os
import pathlib
import subprocess
import tempfile

RUST_MAIN = r'''
use encoding_rs::GB18030;
fn decode(bytes: &[u8]) -> u32 {
    let (text, _, had_errors) = GB18030.decode(bytes);
    let text: String = text.into_owned();
    let mut chars = text.chars();
    let first = chars.next().unwrap();
    if had_errors || chars.next().is_some() { 0 } else { first as u32 }
}
fn main() {
    let mut two = Vec::new();
    for pointer in 0..23940u32 {
        let trail = (pointer % 190) as u8;
        two.push(decode(&[(pointer / 190 + 0x81) as u8, if trail < 0x3F { trail + 0x40 } else { trail + 0x41 }]));
    }
    let mut four = Vec::new();
    for p in 0..39420u32 {
        four.push(decode(&[(p / 12600 + 0x81) as u8, ((p % 12600) / 1260 + 0x30) as u8,
            ((p % 1260) / 10 + 0x81) as u8, (p % 10 + 0x30) as u8]));
    }
    println!("{}", two.iter().map(|c| c.to_string()).collect::<Vec<_>>().join(","));
    println!("{}", four.iter().map(|c| c.to_string()).collect::<Vec<_>>().join(","));
}
'''


def cargo_binary():
    toolchain = pathlib.Path.home() / '.rustup/toolchains/stable-aarch64-apple-darwin/bin/cargo'
    return str(toolchain) if toolchain.exists() else 'cargo'


def dump(version):
    with tempfile.TemporaryDirectory(prefix='gb18030-dump-') as root:
        project = pathlib.Path(root)
        (project / 'src').mkdir()
        (project / 'Cargo.toml').write_text(
            f'[package]\nname = "gb18030dump"\nversion = "0.1.0"\nedition = "2021"\n'
            f'[dependencies]\nencoding_rs = "={version}"\n')
        (project / 'src/main.rs').write_text(RUST_MAIN)
        env = dict(os.environ)
        env['PATH'] = str(pathlib.Path(cargo_binary()).parent) + os.pathsep + env.get('PATH', '')
        output = subprocess.run([cargo_binary(), 'run', '--offline', '-q', '--release'], cwd=project,
                                env=env, check=True, capture_output=True, text=True).stdout
    two, four = output.strip().split('\n')
    return [int(value) for value in two.split(',')], [int(value) for value in four.split(',')]


def compress_ranges(four):
    # Pointer 7457 (U+E7C7) is special-cased by the standard's range lookup.
    ranges = []
    for pointer, code_point in enumerate(four):
        if pointer == 7457:
            continue
        if code_point == 0:
            raise SystemExit(f'four-byte pointer {pointer} is unmapped')
        if not ranges or code_point - pointer != ranges[-1][1] - ranges[-1][0]:
            ranges.append((pointer, code_point))
    return ranges


def rows(values, per_row=12):
    lines = []
    for index in range(0, len(values), per_row):
        lines.append('\t' + ', '.join(values[index:index + per_row]) + ',')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--crate-version', default='0.8.40')
    parser.add_argument('--output', default='encoding/gb18030_data.v')
    args = parser.parse_args()
    two, four = dump(args.crate_version)
    if len(two) != 23940 or 0 in two:
        raise SystemExit('index-gb18030 is incomplete')
    ranges = compress_ranges(four)
    # The encoder's index pointer for a code point is its first pointer.
