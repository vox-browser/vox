pub fn code_point_has_mark_general_category(code_point u32) bool {
	mut low := 0
	mut high := mark_general_category_ranges.len - 1
	for low <= high {
		middle := (low + high) / 2
		range_ := mark_general_category_ranges[middle]
		if code_point < range_[0] {
			high = middle - 1
		} else if code_point > range_[1] {
			low = middle + 1
		} else {
			return true
		}
	}
	return false
}
