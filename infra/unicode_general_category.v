fn code_point_is_in_ranges(code_point u32, ranges [][2]u32) bool {
	mut low := 0
	mut high := ranges.len - 1
	for low <= high {
		middle := (low + high) / 2
		range_ := ranges[middle]
		if code_point < range_[0] {
			high = middle - 1
		} else if code_point > range_[1] {
			low = middle + 1
		} else {
			return true
		}
	}
	return false
}

pub fn code_point_has_mark_general_category(code_point u32) bool {
	return code_point_is_in_ranges(code_point, mark_general_category_ranges)
}

