@[inline]
fn text_boundary_in_grapheme_ranges(r rune, value_start int, interval_count int) bool {
	target := u32(r)
	mut low := 0
	mut high := interval_count
	for low < high {
		mid := low + (high - low) / 2
		lo := text_boundary_grapheme_ranges[value_start + mid * 2]
		hi := text_boundary_grapheme_ranges[value_start + mid * 2 + 1]
		if target < lo {
			high = mid
		} else if target > hi {
			low = mid + 1
		} else {
			return true
		}
	}
	return false
}

@[inline]
fn text_boundary_grapheme_break_property(r rune) TextBoundaryGraphemeProperty {
	if r == `\r` {
		return .cr
	}
	if r == `\n` {
		return .lf
	}
	if r == 0x200d {
		return .zwj
	}
	if r >= 0x1f1e6 && r <= 0x1f1ff {
		return .regional_indicator
	}
	if r >= 0xac00 && r <= 0xd7a3 {
		return if (u32(r) - 0xac00) % 28 == 0 { .lv } else { .lvt }
	}
	if (r >= 0x1100 && r <= 0x115f) || (r >= 0xa960 && r <= 0xa97c) {
		return .l
	}
	if (r >= 0x1160 && r <= 0x11a7) || (r >= 0xd7b0 && r <= 0xd7c6) {
		return .v
	}
	if (r >= 0x11a8 && r <= 0x11ff) || (r >= 0xd7cb && r <= 0xd7fb) {
		return .t
	}
	if text_boundary_in_grapheme_ranges(r, 0, 26) {
		return .control
	}
	if text_boundary_in_grapheme_ranges(r, 52, 358) {
		return .extend
	}
	if text_boundary_in_grapheme_ranges(r, 768, 159) {
		return .spacing_mark
	}
	if text_boundary_in_grapheme_ranges(r, 1086, 13) {
		return .prepend
	}
	return .other
}

@[inline]
fn text_boundary_is_extended_pictographic(r rune) bool {
	return text_boundary_in_grapheme_ranges(r, 1112, 491)
}

struct TextBoundaryGraphemeState {
mut:
	prev_prop                   TextBoundaryGraphemeProperty
	ri_count                    int
	extended_pictographic_state u8
}

@[inline]
fn text_boundary_grapheme_state_from_rune(r rune, prop TextBoundaryGraphemeProperty) TextBoundaryGraphemeState {
	return TextBoundaryGraphemeState{
		prev_prop:                   prop
		ri_count:                    if prop == .regional_indicator { 1 } else { 0 }
		extended_pictographic_state: if text_boundary_is_extended_pictographic(r) {
			u8(1)
		} else {
			u8(0)
		}
	}
}

@[inline]
fn (mut gs TextBoundaryGraphemeState) push(r rune, prop TextBoundaryGraphemeProperty) {
	gs.prev_prop = prop
	gs.ri_count = if prop == .regional_indicator { gs.ri_count + 1 } else { 0 }
	if text_boundary_is_extended_pictographic(r) {
		gs.extended_pictographic_state = 1
	} else if prop == .extend && gs.extended_pictographic_state == 1 {
		// Keep the `Extended_Pictographic Extend*` tail alive for GB11.
	} else if prop == .zwj && gs.extended_pictographic_state == 1 {
		gs.extended_pictographic_state = 2
	} else {
		gs.extended_pictographic_state = 0
	}
}

@[inline]
fn text_boundary_should_break_grapheme(gs TextBoundaryGraphemeState, r rune, prop TextBoundaryGraphemeProperty) bool {
	match gs.prev_prop {
		.cr {
			if prop == .lf {
				return false
			}
			return true
		}
		.lf, .control {
			return true
		}
		.l {
			if prop in [.l, .v, .lv, .lvt] {
				return false
			}
		}
		.lv, .v {
			if prop in [.v, .t] {
				return false
			}
		}
		.lvt, .t {
			if prop == .t {
				return false
			}
		}
		.prepend {
			return false
		}
		.regional_indicator {
			if prop == .regional_indicator && gs.ri_count % 2 == 1 {
				return false
			}
		}
		else {}
	}

	if prop in [.cr, .lf, .control] {
		return true
	}
	if prop in [.extend, .zwj, .spacing_mark] {
		return false
	}
	if gs.extended_pictographic_state == 2 && text_boundary_is_extended_pictographic(r) {
		return false
	}
	return true
}

// Return owned UTF-16 boundary offsets without materializing grapheme strings.
// The caller already decoded code_points with string.runes(); use those exact
// replacement scalars for invalid UTF-8 instead of inspecting original bytes.
fn general_text_grapheme_boundaries(code_points []rune) []int {
	mut boundaries := []int{cap: code_points.len + 1}
	boundaries << 0
	if code_points.len == 0 { return boundaries }
	first := code_points[0]
	first_property := text_boundary_grapheme_break_property(first)
	mut state := text_boundary_grapheme_state_from_rune(first, first_property)
	mut offset := if first > 0xffff { 2 } else { 1 }
	for code_point in code_points[1..] {
		property := text_boundary_grapheme_break_property(code_point)
		if text_boundary_should_break_grapheme(state, code_point, property) {
			boundaries << offset
			state = text_boundary_grapheme_state_from_rune(code_point, property)
		} else {
			state.push(code_point, property)
		}
		offset += if code_point > 0xffff { 2 } else { 1 }
	}
	boundaries << offset
	return boundaries
}
