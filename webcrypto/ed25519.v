fn is_small_order_ed25519_point(point []u8) bool {
	if point.len != 32 { return false }
	for candidate in ed25519_small_order_points {
		if point == candidate { return true }
	}
	return false
}

pub fn generate_ed25519_key(extractable bool, usages []KeyUsage) !CryptoKeyPair {
	validate_ed448_usages(usages, [.sign, .verify])!
	private_bytes := native_edwards_private('Ed25519')!
	public_bytes := native_edwards_public('Ed25519', private_bytes)!
	return CryptoKeyPair{
		public_key:  exchange_key('Ed25519', false, public_bytes, true, usage_intersection(usages, [.verify]))
		private_key: exchange_key('Ed25519', true, private_bytes, extractable, usage_intersection(usages, [.sign]))
	}
}

pub fn ed25519_public_key_from_seed(seed []u8) ![]u8 {
	if seed.len != 32 { return error('DataError: Ed25519 seed must be 32 bytes') }
	return native_edwards_public('Ed25519', seed)
}

pub fn ed25519_sign(key &CryptoKey, message []u8) ![]u8 {
	if key.type_ != .private_key { return error('InvalidAccessError: Key is not a private key') }
	// Upstream derives the public key before invoking the native signing operation.
	native_edwards_public('Ed25519', key.handle_)!
	return native_ed25519_sign(key.handle_, message)
}

pub fn ed25519_verify(key &CryptoKey, signature []u8, message []u8) !bool {
	if key.type_ != .public_key { return error('InvalidAccessError: Key is not a public key') }
	if is_small_order_ed25519_point(key.handle_) { return false }
	if signature.len >= 32 && is_small_order_ed25519_point(signature[..32]) { return false }
	return native_ed25519_verify(key.handle_, signature, message)
}

fn import_ed25519_jwk(jwk JsonWebKey, extractable bool, usages []KeyUsage) !&CryptoKey {
	private_key := jwk.d != none
	validate_ed448_usages(usages, if private_key { [KeyUsage.sign] } else { [KeyUsage.verify] })!
	if (jwk.kty or { '' }) != 'OKP' { return error('DataError: Invalid key type') }
	if (jwk.crv or { '' }) != 'Ed25519' { return error('DataError: Invalid curve') }
	if alg := jwk.alg {
		if alg !in ['Ed25519', 'EdDSA'] { return error('DataError: Invalid algorithm') }
	}
	if usages.len > 0 {
		if use := jwk.use {
			if use != 'sig' { return error('DataError: Invalid key usage') }
		}
	}
	validate_jwk_key_ops(jwk, usages)!
	if ext := jwk.ext {
		if !ext && extractable { return error('DataError: Invalid extractable') }
	}
	public_bytes := base64url_decode(jwk.x or { return error('DataError: Missing x field') })!
	if public_bytes.len != 32 { return error('DataError: Invalid key length') }
	if d := jwk.d {
		private_bytes := base64url_decode(d)!
		if private_bytes.len != 32 { return error('DataError: Invalid key length') }
		if native_edwards_public('Ed25519', private_bytes)! != public_bytes {
			return error('DataError: Invalid key pair')
		}
		return exchange_key('Ed25519', true, private_bytes, false, [])
	}
	return exchange_key('Ed25519', false, public_bytes, false, [])
}

fn import_ed25519_algorithm_key(format KeyFormat, material []u8, extractable bool, usages []KeyUsage) !&CryptoKey {
	match format {
		.spki, .pkcs8 {
			private_key := format == .pkcs8
			validate_ed448_usages(usages, if private_key {
				[KeyUsage.sign]
			} else {
				[KeyUsage.verify]
			})!
			bytes := parse_okp_der('Ed25519', material, private_key) or {
				if err.msg() == 'DataError: Invalid algorithm' {
					return error('DataError: Invalid algorithm identifier')
				}
				return err
			}
			return exchange_key('Ed25519', private_key, bytes, false, [])
		}
		.jwk { return import_ed25519_jwk(JsonWebKey.parse(material)!, extractable, usages) }
		.raw, .raw_public {
			validate_ed448_usages(usages, [.verify])!
			if material.len != 32 { return error('DataError: Invalid key length') }
			return exchange_key('Ed25519', false, material, false, [])
		}
		else { return error('NotSupportedError: Invalid key format') }
	}
}

// Preserve the existing typed V seed/expanded-key convenience boundary.
// These formats are absent from the pinned ED25519 AlgorithmMethods/JS binding.
pub fn import_ed25519_key(format KeyFormat, material []u8, extractable bool, usages []KeyUsage) !&CryptoKey {
	mut key := if format in [.raw_seed, .raw_private] {
		validate_ed448_usages(usages, [.sign])!
		expected := if format == .raw_seed { 32 } else { 64 }
		if material.len != expected { return error('DataError: Invalid key length') }
		exchange_key('Ed25519', true, material[..32], false, [])
	} else {
		import_ed25519_algorithm_key(format, material, extractable, usages)!
	}
	key.set_extractable(extractable)
	key.set_usages(usages)
	return key
}

fn export_ed25519_jwk(key &CryptoKey) !JsonWebKey {
	jwk := export_exchange_jwk('Ed25519', key)!
	return JsonWebKey{ ...jwk, alg: 'Ed25519' }
}

fn export_ed25519_key(format KeyFormat, key &CryptoKey) ![]u8 {
	if format == .jwk { return export_ed25519_jwk(key)!.to_json().bytes() }
	return export_exchange_key('Ed25519', format, key)
}
